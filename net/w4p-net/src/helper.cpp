	void Helper::HandleCommand(const std::string& raw)
	{
		std::string line = raw;
		while (!line.empty() && (line.back() == '\r' || line.back() == '\n' || line.back() == ' '))
			line.pop_back();
		if (line.empty())
			return;
		if (line.find("W4P") != std::string::npos || line.find("w4p") != std::string::npos)
		{
			HandlePaste(line);
			return;
		}
		std::istringstream is(line);
		std::string cmd;
		is >> cmd;
		if (cmd == "quit" || cmd == "exit")
			quit_.store(true);
		else if (cmd == "status")
			Summary(false);
		else if (cmd == "lock")
		{
			lobby_open_ = false;
			Say("Lobby closed: no new players.");
		}
		else if (cmd == "probe")
		{
			double rate = 60, secs = 60;
			int size = 200;
			is >> rate >> size >> secs;
			if (probe_running_.load())
			{
				Say("A probe is already running.");
				return;
			}
			if (probe_thread_.joinable())
				probe_thread_.join();
			for (auto& st : slot_stats_)
			{
				std::lock_guard<std::mutex> lock(st.mx);
				st.probe_seen.clear();
				st.probe_rtt_ms.clear();
				st.probe_tx = st.probe_rx = st.probe_rx_dup = st.probe_echo_rx = st.probe_no_route = 0;
				st.probe_tx_via_host = 0;
			}
			probe_rate_ = rate;
			probe_size_ = size;
			probe_seconds_ = secs;
			probe_start_us_ = NowUs();
			probe_end_us_ = 0;
			probe_running_.store(true);
			probe_done_reported_ = false;
			Log("probe started: %.0f datagrams/s of %d bytes to every other player for %.0f s", rate, size, secs);
			probe_thread_ = std::thread([this, rate, size, secs] { ProbeThread(rate, size, secs); });
		}
		else
			Say("Unknown command '%s' (paste a code, or: status, probe RATE SIZE SECONDS, lock, quit).", cmd.c_str());
	}

	void Helper::HandlePaste(const std::string& line)
	{
		CodeRecord r;
		const CodeError e = ParseCode(line, &r);
		if (e != CodeError::None)
		{
			Say("%s", CodeErrorMessage(e));
			Event("error paste %d", static_cast<int>(e));
			return;
		}
		if (!is_host_)
		{
			Say("Only the host pastes reply codes.");
			return;
		}
		if (r.kind != CodeKind::Reply)
		{
			Say("This is a join code. Paste the reply code your friend sent.");
			Event("error paste kind");
			return;
		}
		if (std::memcmp(r.tag.data(), tag_, kTagShortSize) != 0)
		{
			Say("This reply code belongs to another game (an old join code?). Ask your friend to join again.");
			Event("error paste session");
			return;
		}
		Link* L = FindByNonce(r.nonce);
		if (L)
		{
			if (L->Connected())
			{
				Say("Player %d is already connected.", L->peer_slot.load() + 1);
				return;
			}
			L->remote_cands = r.cands;
			L->remote_end = true;
			StopAgent(L);
			StartAgent(L);
			Log("reply code for an existing link %d (from a direct dial): agent restarted with %zu candidates", L->index,
				r.cands.size());
			Event("path a %d", L->peer_slot.load());
			return;
		}
		const int slot = lobby_open_ ? FreeSlot(-1) : -1;
		if (slot < 0)
		{
			Say(lobby_open_ ? "The game is full (%d players)." : "The lobby is closed.", players_);
			Event("error paste full");
			return;
		}
		L = NewLink(Link::Kind::HostToJoiner);
		L->nonce = r.nonce;
		SetupHostJoinerCreds(L, true);
		L->controlling = true;
		L->remote_cands = r.cands;
		L->remote_end = true;
		L->path = 'a';
		L->peer_slot.store(slot);
		slot_link_[slot].store(L);
		Log("reply code accepted: joiner %s, %zu candidate(s), reserved slot %d (path a)",
			Hex(r.nonce.data(), 2).c_str(), r.cands.size(), slot);
		StartAgent(L);
		Event("path a %d", slot);
		Say("Reply code accepted (Player %d). Connecting...", slot + 1);
	}

	void Helper::HandleIncoming(const Incoming& in)
	{
		std::array<uint8_t, kNonceSize> n{};
		const bool ok = in.remote_ufrag.size() == 9 && in.remote_ufrag[0] == 'J' &&
						Base32Decode(in.remote_ufrag.substr(1), n.data(), kNonceSize);
		if (!is_host_ || !ok)
		{
			if (strangers_++ < 20)
				Log("connectivity check with unknown credentials ignored (%s)", is_host_ ? "not a joiner" : "no such link");
			return;
		}
		uint8_t hu8[8];
		Put64(hu8, Prf(secret_.data(), "hu", n.data(), kNonceSize));
		if (in.local_ufrag != "H" + Base32Plain(hu8, 8))
		{
			if (strangers_++ < 20)
				Log("connectivity check from a joiner of another session rejected");
			return;
		}
		const std::string key = Hex(n.data(), kNonceSize);
		const bool first = std::find(incoming_seen_.begin(), incoming_seen_.end(), key) == incoming_seen_.end();
		if (first)
			incoming_seen_.push_back(key);
		if (opt_.test_no_direct_dial)
		{
			if (first)
				Log("direct dial from joiner %s ignored [TEST SWITCH --test-no-direct-dial]", Hex(n.data(), 2).c_str());
			return;
		}
		if (FindByNonce(n))
			return; // agent exists (being created or re-created)
		const int slot = lobby_open_ ? FreeSlot(-1) : -1;
		if (slot < 0)
		{
			if (first)
				Log("direct dial refused: %s", lobby_open_ ? "game full" : "lobby closed");
			return;
		}
		Link* L = NewLink(Link::Kind::HostToJoiner);
		L->nonce = n;
		SetupHostJoinerCreds(L, true);
		L->controlling = true;
		L->remote_end = false; // candidates unknown: learned as peer-reflexive from the joiner's checks
		L->path = 'b';
		L->peer_slot.store(slot);
		slot_link_[slot].store(L);
		Log("direct dial from joiner %s (address class %s): reserved slot %d (path b)", Hex(n.data(), 2).c_str(),
			[&] {
				Candidate c;
				return Candidate::FromString(in.address, in.port, CandType::Prflx, &c) ? c.ClassName() : std::string("?");
			}()
				.c_str(),
			slot);
		StartAgent(L);
		Event("path b %d", slot);
	}

	void Helper::SendRoster()
	{
		std::vector<uint8_t> b = {CT_ROSTER, static_cast<uint8_t>(players_), occupied_.load()};
		for (int s = 1; s < kMaxSlots; s++)
		{
			Link* L = slot_link_[s].load();
			if (L && L->welcomed && L->Connected())
				SendCtrl(L, b);
		}
	}

	void Helper::HandleCtrl(const CtrlMsg& m)
	{
		Link* L = m.link;
		const std::vector<uint8_t>& b = m.body;
		const uint8_t ct = b[0];
		if (L->kind == Link::Kind::HostToJoiner)
		{
			if (ct == CT_HELLO && b.size() >= 3)
			{
				const int want = b[1] == kNoSlot ? -1 : b[1];
				const int proto = b[2];
				const uint8_t* p = b.data() + 3;
				std::vector<Candidate> cands;
				ReadCandidates(p, b.data() + b.size(), &cands);
				if (proto != kHelperProto)
				{
					Say("A player uses a different version of w4p-net (protocol %d, ours %d).", proto, kHelperProto);
					SendCtrl(L, {CT_WELCOME, static_cast<uint8_t>(L->peer_slot.load()), static_cast<uint8_t>(players_), 1});
					return;
				}
				if (!L->welcomed)
				{
					int cur = L->peer_slot.load();
					if (want >= 1 && want < players_ && want != cur && !slot_link_[want].load())
					{
						slot_link_[cur].store(nullptr);
						slot_link_[want].store(L);
						L->peer_slot.store(want);
						cur = want;
					}
					L->welcomed = true;
					L->peer_desc = cands;
					occupied_.fetch_or(static_cast<uint8_t>(1u << cur));
					const double ms = (NowUs() - L->first_start_us) / 1000.0;
					Say("Player %d joined (path %c; connected %.1f ms after the agent started).", cur + 1, L->path,
						(L->connected_us - L->first_start_us) / 1000.0);
					Event("joined %d %c %.1f", cur, L->path, ms);
					for (const Candidate& c : cands)
						Log("  player %d candidate: %s", cur + 1, MaskCand(c).c_str());
				}
				SendCtrl(L, {CT_WELCOME, static_cast<uint8_t>(L->peer_slot.load()), static_cast<uint8_t>(players_), 0});
				SendRoster();
			}
			else if (ct == CT_INTRO_ACK && b.size() >= 2 + kNonceSize)
			{
				const int me_slot = L->peer_slot.load();
				const int peer = b[1];
				for (Intro& in : intros_)
				{
					if (std::memcmp(in.nonce.data(), b.data() + 2, kNonceSize) != 0)
						continue;
					if (in.a == me_slot && in.b == peer)
						in.ack_a = true;
					if (in.b == me_slot && in.a == peer)
						in.ack_b = true;
				}
			}
			else if (ct == CT_STATUS && b.size() >= 2 + 3 * kMaxSlots)
			{
				const uint8_t ready = b[1];
				bool changed = ready != L->status_ready;
				for (int s = 0; s < kMaxSlots; s++)
				{
					const uint8_t route = b[2 + 3 * s];
					const uint16_t rtt = static_cast<uint16_t>(b[3 + 3 * s] | (b[4 + 3 * s] << 8));
					if (route != L->status_route[s])
						changed = true;
					L->status_route[s] = route;
					L->status_rtt[s] = rtt;
				}
				L->status_ready = ready;
				if (changed)
				{
					const int me_slot = L->peer_slot.load();
					for (int s = 1; s < kMaxSlots; s++)
					{
						if (s == me_slot || !(occupied_.load() & (1u << s)))
							continue;
						Log("Player %d <-> Player %d: %s (RTT p50 %.1f ms, reported by Player %d)", me_slot + 1, s + 1,
							RouteName(L->status_route[s]), L->status_rtt[s] / 10.0, me_slot + 1);
					}
				}
			}
			else if (ct == CT_BYE)
			{
				Say("Player %d left.", L->peer_slot.load() + 1);
				Event("left %d", L->peer_slot.load());
			}
			return;
		}
		if (L->kind == Link::Kind::JoinerToHost)
		{
			if (ct == CT_WELCOME && b.size() >= 4)
			{
				if (b[3] != 0)
				{
					Say("The host refused the connection (different w4p-net version).");
					Event("error refused");
					quit_.store(true);
					return;
				}
				if (!welcomed_)
				{
					welcomed_ = true;
					my_slot_.store(b[1]);
					players_ = b[2];
					Event("slot %d", b[1]);
					Say("Connected to the host. You are Player %d.", b[1] + 1);
				}
			}
			else if (ct == CT_ROSTER && b.size() >= 3)
			{
				players_ = b[1];
				occupied_.store(b[2]);
			}
			else if (ct == CT_INTRO && b.size() >= 3 + kNonceSize)
			{
				const int me = my_slot_.load();
				const int peer = b[1];
				if (me == kNoSlot || peer >= kMaxSlots || peer == me || peer == 0)
					return;
				std::array<uint8_t, kNonceSize> nonce;
				std::memcpy(nonce.data(), b.data() + 3, kNonceSize);
				const uint8_t* p = b.data() + 3 + kNonceSize;
				std::vector<Candidate> cands;
				ReadCandidates(p, b.data() + b.size(), &cands);
				Link* existing = slot_link_[peer].load();
				if (!existing || existing->nonce != nonce)
				{
					if (existing)
					{
						StopAgent(existing);
						Log("link %d replaced by a new introduction", existing->index);
					}
					Link* N = NewLink(Link::Kind::Pair);
					N->peer_slot.store(peer);
					N->nonce = nonce;
					SetupPairCreds(N, me, peer);
					N->controlling = me < peer;
					N->remote_cands = cands;
					N->remote_end = true;
					N->path = 'i';
					N->blocked = std::find(opt_.test_block_peers.begin(), opt_.test_block_peers.end(), peer) !=
								 opt_.test_block_peers.end();
					slot_link_[peer].store(N);
					Log("introduced to Player %d by the host (%zu candidate(s))", peer + 1, cands.size());
					StartAgent(N);
				}
				std::vector<uint8_t> ack = {CT_INTRO_ACK, static_cast<uint8_t>(peer)};
				ack.insert(ack.end(), nonce.begin(), nonce.end());
				SendCtrl(L, ack);
			}
			else if (ct == CT_BYE)
			{
				Say("The host closed the game.");
				Event("host_left");
			}
			return;
		}
		if (ct == CT_BYE)
		{
			Say("Player %d left.", L->peer_slot.load() + 1);
			Event("left %d", L->peer_slot.load());
		}
	}

	void Helper::CheckLinks()
	{
		const int64_t now = NowUs();
		for (auto& lp : links_)
		{
			Link* L = lp.get();
			if (!L->agent.load())
				continue;
			const int st = L->state.load();
			if (st != L->seen_state)
			{
				const double ms = (L->state_us.load() - L->agent_start_us) / 1000.0;
				Log("link %d (peer slot %d): %s (%.1f ms after agent #%d started)", L->index, L->peer_slot.load(),
					juice_state_to_string(static_cast<juice_state_t>(st)), ms, L->attempts);
				if ((st == JUICE_STATE_CONNECTED || st == JUICE_STATE_COMPLETED) &&
					!(L->seen_state == JUICE_STATE_CONNECTED || L->seen_state == JUICE_STATE_COMPLETED))
				{
					char lc[JUICE_MAX_CANDIDATE_SDP_STRING_LEN] = {}, rc[JUICE_MAX_CANDIDATE_SDP_STRING_LEN] = {};
					{
						std::shared_lock<std::shared_mutex> lock(L->agent_mx);
						if (juice_agent_t* a = L->agent.load())
							juice_get_selected_candidates(a, lc, sizeof(lc), rc, sizeof(rc));
					}
					L->sel_local = MaskSdpCand(lc);
					L->sel_remote = MaskSdpCand(rc);
					const bool again = L->ever_connected;
					L->ever_connected = true;
					L->connected_us = L->conn_cb_us.load() ? L->conn_cb_us.load() : L->state_us.load();
					L->lost_us = 0;
					const double total = (L->connected_us - L->first_start_us) / 1000.0;
					Log("link %d connected%s: %.1f ms after the first agent start (attempt %d); selected pair: local %s, "
						"remote %s",
						L->index, again ? " again" : "", total, L->attempts, L->sel_local.c_str(), L->sel_remote.c_str());
					Event("link %d connected %.1f %d %c", L->peer_slot.load(), total, L->attempts, L->path);
					if (L->kind == Link::Kind::JoinerToHost && !again)
						Say("Connected to the host (%.1f ms).", total);
				}
				if (st == JUICE_STATE_FAILED)
					Event("link %d failed %d", L->peer_slot.load(), L->attempts);
				L->seen_state = st;
			}
			if (st == JUICE_STATE_FAILED)
			{
				if (L->ever_connected && L->lost_us == 0)
				{
					L->lost_us = now;
					Say("Connection to Player %d lost; trying again.", L->peer_slot.load() + 1);
				}
				const int64_t window_start = L->ever_connected ? L->lost_us : L->first_start_us;
				if (now - window_start < static_cast<int64_t>(opt_.connect_minutes) * 60000000LL)
				{
					Log("link %d: agent #%d failed; re-creating it with the same port, credentials and remote description",
						L->index, L->attempts);
					StopAgent(L);
					StartAgent(L);
				}
				else if (!L->gave_up)
				{
					L->gave_up = true;
					StopAgent(L);
					Event("link %d gave_up", L->peer_slot.load());
					if (L->kind == Link::Kind::Pair)
						Say("Player %d and you cannot connect directly; your inputs go through the host.",
							L->peer_slot.load() + 1);
					else
						Say("Could not connect directly. This happens with some internet providers and phone hotspots. "
							"(1) Let another player host. (2) Allow w4p-net in Windows Firewall. (3) Use the VPN way "
							"(README). (4) Send us connection-log.txt.");
					if (is_host_ && !L->welcomed && slot_link_[L->peer_slot.load()].load() == L)
						slot_link_[L->peer_slot.load()].store(nullptr);
				}
			}
		}
	}

	void Helper::HostIntroductions()
	{
		const int64_t now = NowUs();
		std::vector<int> ready;
		for (int s = 1; s < kMaxSlots; s++)
		{
			Link* L = slot_link_[s].load();
			if (L && L->welcomed && L->Connected())
				ready.push_back(s);
		}
		for (size_t i = 0; i < ready.size(); i++)
			for (size_t j = i + 1; j < ready.size(); j++)
			{
				const int a = ready[i], b = ready[j];
				Link* la = slot_link_[a].load();
				Link* lb = slot_link_[b].load();
				bool found = false;
				for (const Intro& in : intros_)
					if (in.a == a && in.b == b && in.la == la && in.lb == lb)
						found = true;
				if (!found)
				{
					Intro in;
					in.a = a;
					in.b = b;
					in.la = la;
					in.lb = lb;
					RandomBytes(in.nonce.data(), kNonceSize);
					intros_.push_back(in);
					Log("introducing Player %d and Player %d to each other", a + 1, b + 1);
				}
			}
		for (Intro& in : intros_)
		{
			if ((in.ack_a && in.ack_b) || now - in.last_send_us < 250000)
				continue;
			Link* la = slot_link_[in.a].load();
			Link* lb = slot_link_[in.b].load();
			if (la != in.la || lb != in.lb || !la || !lb)
				continue; // superseded
			in.last_send_us = now;
			auto body = [&](int peer, uint8_t role, const std::vector<Candidate>& desc) {
				std::vector<uint8_t> v = {CT_INTRO, static_cast<uint8_t>(peer), role};
				v.insert(v.end(), in.nonce.begin(), in.nonce.end());
				AppendCandidates(v, desc);
				return v;
			};
			if (!in.ack_a)
				SendCtrl(la, body(in.b, 1, lb->peer_desc));
			if (!in.ack_b)
				SendCtrl(lb, body(in.a, 0, la->peer_desc));
		}
	}

	uint8_t Helper::RouteState(int slot)
	{
		const int me = my_slot_.load();
		if (slot == me)
			return ROUTE_SELF;
		Link* d = slot_link_[slot].load();
		if (d && d->Connected() && !d->blocked)
			return ROUTE_DIRECT;
		if (!is_host_ && slot != 0)
		{
			Link* h = slot_link_[0].load();
			const bool host_ok = h && h->Connected();
			if (d && host_ok && (d->blocked || d->gave_up || d->attempts > 1))
				return ROUTE_HOST; // direct link failed at least once (or blocked by the test switch): forwarded
			if (d)
				return ROUTE_CONNECTING;
		}
		if (d)
			return ROUTE_CONNECTING;
		return ROUTE_NONE;
	}

	void Helper::JoinerStatus()
	{
		Link* h = slot_link_[0].load();
		if (!h || !h->Connected())
			return;
		std::vector<uint8_t> b = {CT_STATUS, static_cast<uint8_t>(ready_ ? 1 : 0)};
		for (int s = 0; s < kMaxSlots; s++)
		{
			const uint8_t r = (occupied_.load() & (1u << s)) ? RouteState(s) : ROUTE_NONE;
			uint16_t rtt = 0;
			if (Link* L = slot_link_[s].load())
			{
				std::lock_guard<std::mutex> lock(L->rtt_mx);
				const size_t n = L->ping_rtt_ms.size();
				std::vector<float> last(L->ping_rtt_ms.begin() + (n > 40 ? n - 40 : 0), L->ping_rtt_ms.end());
				const float p50 = Pct(last, 0.5);
				rtt = p50 < 0 ? 0 : static_cast<uint16_t>(std::min(65535.0f, p50 * 10.0f));
			}
			b.push_back(r);
			b.push_back(static_cast<uint8_t>(rtt & 0xFF));
			b.push_back(static_cast<uint8_t>(rtt >> 8));
		}
		SendCtrl(h, b);
	}

	void Helper::Pings()
	{
		for (auto& lp : links_)
		{
			Link* L = lp.get();
			if (!L->agent.load() || !L->Connected())
				continue;
			std::vector<uint8_t> b = {CT_PING};
			Put32(b, L->ping_seq++);
			Put64(b, static_cast<uint64_t>(NowUs()));
			SendCtrl(L, b);
		}
	}

	void Helper::ReadyCheck()
	{
		bool r = false;
		if (is_host_)
		{
			int n = 0;
			bool all = true;
			for (int s = 1; s < players_; s++)
			{
				Link* L = slot_link_[s].load();
				if (L && L->welcomed && L->Connected())
				{
					n++;
					if (!L->status_ready)
						all = false;
				}
				else
					all = false;
			}
			r = all && n == players_ - 1;
		}
		else if (welcomed_)
		{
			r = true;
			const uint8_t mask = occupied_.load();
			for (int s = 0; s < kMaxSlots; s++)
			{
				if (!(mask & (1u << s)) || s == my_slot_.load())
					continue;
				const uint8_t st = RouteState(s);
				if (st != ROUTE_DIRECT && st != ROUTE_HOST)
					r = false;
			}
		}
		if (r != ready_)
		{
			ready_ = r;
			if (r)
			{
				Event("ready %.1f", (NowUs() - t0_us_) / 1000.0);
				if (is_host_)
					Say("All %d players are connected. (Press Start in the launcher.)", players_);
			}
			else
				Event("notready");
		}
	}

	void Helper::Summary(bool final)
	{
		Log("---- %s summary (role %s, slot %d) ----", final ? "final" : "periodic", is_host_ ? "host" : "joiner",
			my_slot_.load());
		for (auto& lp : links_)
		{
			Link* L = lp.get();
			std::vector<float> r;
			{
				std::lock_guard<std::mutex> lock(L->rtt_mx);
				r = L->ping_rtt_ms;
			}
			Log("link %d %s peer slot %d path %c%s: state %s, attempts %d, %s; ping RTT n=%zu p50=%.3f p95=%.3f "
				"max=%.3f ms; sent %llu dgr/%llu B, received %llu dgr/%llu B, forwarded %llu, rejected tag %llu mac %llu "
				"src %llu, send errors %llu",
				L->index, KindName(L->kind), L->peer_slot.load(), L->path, L->blocked ? " [blocked]" : "",
				L->agent.load() ? juice_state_to_string(static_cast<juice_state_t>(L->state.load())) : "stopped",
				L->attempts,
				L->ever_connected ? ("selected local " + L->sel_local + " / remote " + L->sel_remote).c_str() : "never connected",
				r.size(), Pct(r, 0.5), Pct(r, 0.95), Pct(r, 1.0), static_cast<unsigned long long>(L->tx.load()),
				static_cast<unsigned long long>(L->tx_bytes.load()), static_cast<unsigned long long>(L->rx.load()),
				static_cast<unsigned long long>(L->rx_bytes.load()), static_cast<unsigned long long>(L->fwd_out.load()),
				static_cast<unsigned long long>(L->bad_tag.load()), static_cast<unsigned long long>(L->bad_mac.load()),
				static_cast<unsigned long long>(L->bad_src.load()), static_cast<unsigned long long>(L->send_err.load()));
			if (final && !r.empty())
				Log("  ping RTT histogram (ms): %s", Histogram(r).c_str());
		}
		for (int s = 0; s < kMaxSlots; s++)
		{
			SlotStats& st = slot_stats_[s];
			if (!st.data_tx && !st.data_rx && !st.probe_tx && !st.probe_rx)
				continue;
			std::vector<float> pr;
			{
				std::lock_guard<std::mutex> lock(st.mx);
				pr = st.probe_rtt_ms;
			}
			Log("slot %d: emulator data sent %llu (%llu through the host, %llu without route), received %llu (%llu through "
				"the host); probes sent %llu (%llu through the host, %llu without route), received %llu unique (+%llu dup), "
				"echoes %llu, echo RTT p50=%.3f p95=%.3f p99=%.3f max=%.3f ms",
				s, static_cast<unsigned long long>(st.data_tx.load()),
				static_cast<unsigned long long>(st.data_tx_via_host.load()),
				static_cast<unsigned long long>(st.data_no_route.load()), static_cast<unsigned long long>(st.data_rx.load()),
				static_cast<unsigned long long>(st.data_rx_via_host.load()),
				static_cast<unsigned long long>(st.probe_tx.load()), static_cast<unsigned long long>(st.probe_tx_via_host.load()),
				static_cast<unsigned long long>(st.probe_no_route.load()), static_cast<unsigned long long>(st.probe_rx.load()),
				static_cast<unsigned long long>(st.probe_rx_dup.load()),
				static_cast<unsigned long long>(st.probe_echo_rx.load()), Pct(pr, 0.5), Pct(pr, 0.95), Pct(pr, 0.99),
				Pct(pr, 1.0));
			if (final && !pr.empty())
				Log("  probe echo RTT histogram (ms): %s", Histogram(pr).c_str());
		}
		Log("emulator bridge: from emulator %llu, to emulator %llu, dropped %llu, loopback strangers %llu; connectivity "
			"checks with unknown credentials %llu",
			static_cast<unsigned long long>(emu_rx_.load()), static_cast<unsigned long long>(emu_tx_.load()),
			static_cast<unsigned long long>(emu_drop_.load()), static_cast<unsigned long long>(loop_strangers_.load()),
			static_cast<unsigned long long>(strangers_));
	}

