	size_t Helper::Wrap(uint8_t* out, uint8_t type, uint8_t src, uint8_t dst, uint8_t flags, const uint8_t key[16],
		const void* payload, size_t n) const
	{
		out[0] = type;
		out[1] = src;
		out[2] = dst;
		out[3] = flags;
		std::memcpy(out + 4, tag_, 8);
		if (n)
			std::memcpy(out + kHdr, payload, n);
		const uint64_t mac = SipHash24(key, out, kHdr + n);
		Put64(out + kHdr + n, mac);
		return kHdr + n + kMac;
	}

	bool Helper::SendRaw(Link* L, const uint8_t* buf, size_t n)
	{
		std::shared_lock<std::shared_mutex> lock(L->agent_mx);
		juice_agent_t* a = L->agent.load();
		if (!a || !L->Connected())
			return false;
		if (juice_send(a, reinterpret_cast<const char*>(buf), n) != JUICE_ERR_SUCCESS)
		{
			L->send_err++;
			return false;
		}
		L->tx++;
		L->tx_bytes += n;
		return true;
	}

	Link* Helper::Route(int dst, bool* via_host)
	{
		*via_host = false;
		if (dst < 0 || dst >= kMaxSlots)
			return nullptr;
		Link* d = slot_link_[dst].load();
		if (d && d->Connected() && !d->blocked)
			return d;
		if (!is_host_ && dst != 0)
		{
			Link* h = slot_link_[0].load();
			if (h && h->Connected())
			{
				*via_host = true;
				return h;
			}
		}
		return nullptr;
	}

	bool Helper::SendTo(int dst, uint8_t type, const void* payload, size_t n, bool* via_host)
	{
		const int me = my_slot_.load();
		if (me == kNoSlot || n + kOverhead > kMaxDgram)
			return false;
		Link* L = Route(dst, via_host);
		if (!L)
			return false;
		uint8_t buf[kMaxDgram];
		const size_t len = Wrap(buf, type, static_cast<uint8_t>(me), static_cast<uint8_t>(dst), 0, L->key, payload, n);
		return SendRaw(L, buf, len);
	}

	bool Helper::SendCtrl(Link* L, const std::vector<uint8_t>& body)
	{
		if (body.size() + kOverhead > kMaxDgram)
			return false;
		uint8_t buf[kMaxDgram];
		const int me = my_slot_.load();
		const size_t len = Wrap(buf, kTypeCtrl, static_cast<uint8_t>(me), static_cast<uint8_t>(L->peer_slot.load()), 0,
			L->key, body.data(), body.size());
		return SendRaw(L, buf, len);
	}

	void Helper::DeliverToEmu(int src, const uint8_t* p, size_t n)
	{
		sockaddr_in a = {};
		a.sin_family = AF_INET;
		a.sin_port = htons(static_cast<u_short>(opt_.emu_port));
		a.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
		if (sendto(static_cast<SOCKET>(slot_sock_[src]), reinterpret_cast<const char*>(p), static_cast<int>(n), 0,
				reinterpret_cast<sockaddr*>(&a), sizeof(a)) >= 0)
			emu_tx_++;
	}

	void Helper::OnRecv(Link* L, const uint8_t* data, size_t size)
	{
		// Runs on libjuice's mux thread. Only authenticated datagrams are acted on (no reply to strangers).
		if (size < kOverhead || std::memcmp(data + 4, tag_, 8) != 0)
		{
			L->bad_tag++;
			return;
		}
		const uint64_t mac = SipHash24(L->key, data, size - kMac);
		if (Get64(data + size - kMac) != mac)
		{
			L->bad_mac++;
			return;
		}
		L->rx++;
		L->rx_bytes += size;
		const uint8_t type = data[0], src = data[1], dst = data[2], flags = data[3];
		const uint8_t* payload = data + kHdr;
		const size_t plen = size - kOverhead;
		const int me = my_slot_.load();
		const int peer = L->peer_slot.load();
		switch (L->kind)
		{
			case Link::Kind::HostToJoiner:
				if (src != peer && !(src == kNoSlot && type == kTypeCtrl))
				{
					L->bad_src++;
					return;
				}
				break;
			case Link::Kind::JoinerToHost:
				if (src != 0 && !((flags & kFlagFwd) && src < kMaxSlots && src != me))
				{
					L->bad_src++;
					return;
				}
				break;
			case Link::Kind::Pair:
				if (src != peer)
				{
					L->bad_src++;
					return;
				}
				break;
		}
		if (type == kTypeCtrl)
		{
			if (plen < 1)
				return;
			if (payload[0] == CT_PING && plen >= 13)
			{
				std::vector<uint8_t> pong(payload, payload + 13);
				pong[0] = CT_PONG;
				SendCtrl(L, pong);
				return;
			}
			if (payload[0] == CT_PONG && plen >= 13)
			{
				const float rtt = static_cast<float>(NowUs() - static_cast<int64_t>(Get64(payload + 5))) / 1000.0f;
				std::lock_guard<std::mutex> lock(L->rtt_mx);
				if (L->ping_rtt_ms.size() < 1000000)
					L->ping_rtt_ms.push_back(rtt);
				L->pongs++;
				return;
			}
			CtrlMsg m;
			m.link = L;
			m.src = src;
			m.body.assign(payload, payload + plen);
			std::lock_guard<std::mutex> lock(q_mx_);
			if (ctrl_.size() < 256)
				ctrl_.push_back(std::move(m));
			return;
		}
		if (dst != me)
		{
			// Forwarding through the host for a joiner pair without a direct link (design 2.3).
			if (is_host_ && dst < kMaxSlots && dst != 0)
			{
				Link* out = slot_link_[dst].load();
				if (out && out->Connected())
				{
					uint8_t buf[kMaxDgram];
					const size_t len = Wrap(buf, type, src, dst, static_cast<uint8_t>(flags | kFlagFwd), out->key, payload, plen);
					if (SendRaw(out, buf, len))
						L->fwd_out++;
				}
			}
			return;
		}
		if (src >= kMaxSlots)
			return;
		SlotStats& st = slot_stats_[src];
		const bool via = (flags & kFlagFwd) != 0;
		if (type == kTypeData)
		{
			DeliverToEmu(src, payload, plen);
			st.data_rx++;
			st.data_rx_bytes += plen;
			if (via)
				st.data_rx_via_host++;
		}
		else if (type == kTypeProbe && plen >= 12)
		{
			const uint32_t seq = Get32(payload);
			{
				std::lock_guard<std::mutex> lock(st.mx);
				if (seq < 4000000)
				{
					if (st.probe_seen.size() <= seq)
						st.probe_seen.resize(seq + 1, 0);
					if (st.probe_seen[seq])
						st.probe_rx_dup++;
					else
					{
						st.probe_seen[seq] = 1;
						st.probe_rx++;
					}
				}
			}
			bool v = false;
			SendTo(src, kTypeEcho, payload, 12, &v);
		}
		else if (type == kTypeEcho && plen >= 12)
		{
			const float rtt = static_cast<float>(NowUs() - static_cast<int64_t>(Get64(payload + 4))) / 1000.0f;
			std::lock_guard<std::mutex> lock(st.mx);
			if (st.probe_rtt_ms.size() < 4000000)
				st.probe_rtt_ms.push_back(rtt);
			st.probe_echo_rx++;
		}
	}

	void Helper::BridgeThread()
	{
		WSAPOLLFD fds[kMaxSlots];
		for (int p = 0; p < kMaxSlots; p++)
		{
			fds[p].fd = static_cast<SOCKET>(slot_sock_[p]);
			fds[p].events = POLLRDNORM;
			fds[p].revents = 0;
		}
		uint8_t buf[kMaxDgram + 64];
		while (!bridge_stop_.load())
		{
			for (auto& f : fds)
				f.revents = 0;
			const int r = WSAPoll(fds, kMaxSlots, 50);
			if (r <= 0)
				continue;
			for (int p = 0; p < kMaxSlots; p++)
			{
				if (!fds[p].revents)
					continue;
				for (;;)
				{
					sockaddr_in from = {};
					int flen = sizeof(from);
					const int n = recvfrom(fds[p].fd, reinterpret_cast<char*>(buf), sizeof(buf), 0,
						reinterpret_cast<sockaddr*>(&from), &flen);
					if (n < 0)
					{
						const int e = WSAGetLastError();
						if (e == WSAECONNRESET)
							continue;
						break; // WSAEWOULDBLOCK or error
					}
					if (from.sin_addr.s_addr != htonl(INADDR_LOOPBACK) || ntohs(from.sin_port) != opt_.emu_port)
					{
						loop_strangers_++; // only the local emulator may use the bridge
						continue;
					}
					emu_rx_++;
					const int me = my_slot_.load();
					if (me == kNoSlot || p == me || !(occupied_.load() & (1u << p)) ||
						static_cast<size_t>(n) + kOverhead > kMaxDgram)
					{
						emu_drop_++;
						continue;
					}
					bool via = false;
					SlotStats& st = slot_stats_[p];
					if (SendTo(p, kTypeData, buf, static_cast<size_t>(n), &via))
					{
						st.data_tx++;
						st.data_tx_bytes += static_cast<uint64_t>(n);
						if (via)
							st.data_tx_via_host++;
					}
					else
						st.data_no_route++;
				}
			}
		}
	}

	void Helper::ProbeThread(double rate, int size, double seconds)
	{
#ifdef _WIN32
		timeBeginPeriod(1);
#endif
		const size_t plen = static_cast<size_t>(std::max<int>(12, size - static_cast<int>(kOverhead)));
		std::vector<uint8_t> body(plen, 0);
		const long long count = static_cast<long long>(rate * seconds);
		const auto start = std::chrono::steady_clock::now();
		const auto step = std::chrono::duration<double>(1.0 / rate);
		for (long long k = 0; k < count && !quit_.load(); k++)
		{
			std::this_thread::sleep_until(start + std::chrono::duration_cast<std::chrono::steady_clock::duration>(step * k));
			const uint8_t mask = occupied_.load();
			const int me = my_slot_.load();
			for (int d = 0; d < kMaxSlots; d++)
			{
				if (d == me || !(mask & (1u << d)))
					continue;
				Put32(body.data(), static_cast<uint32_t>(k));
				Put64(body.data() + 4, static_cast<uint64_t>(NowUs()));
				bool via = false;
				SlotStats& st = slot_stats_[d];
				if (SendTo(d, kTypeProbe, body.data(), body.size(), &via))
				{
					st.probe_tx++;
					if (via)
						st.probe_tx_via_host++;
				}
				else
					st.probe_no_route++;
			}
		}
#ifdef _WIN32
		timeEndPeriod(1);
#endif
		probe_end_us_ = NowUs();
		probe_running_.store(false);
	}

