		void Put32(std::vector<uint8_t>& v, uint32_t x)
		{
			for (int i = 0; i < 4; i++)
				v.push_back(static_cast<uint8_t>(x >> (8 * i)));
		}
		void Put64(std::vector<uint8_t>& v, uint64_t x)
		{
			for (int i = 0; i < 8; i++)
				v.push_back(static_cast<uint8_t>(x >> (8 * i)));
		}
		void Put32(uint8_t* p, uint32_t x)
		{
			for (int i = 0; i < 4; i++)
				p[i] = static_cast<uint8_t>(x >> (8 * i));
		}
		void Put64(uint8_t* p, uint64_t x)
		{
			for (int i = 0; i < 8; i++)
				p[i] = static_cast<uint8_t>(x >> (8 * i));
		}
		uint32_t Get32(const uint8_t* p)
		{
			uint32_t x = 0;
			for (int i = 3; i >= 0; i--)
				x = (x << 8) | p[i];
			return x;
		}
		uint64_t Get64(const uint8_t* p)
		{
			uint64_t x = 0;
			for (int i = 7; i >= 0; i--)
				x = (x << 8) | p[i];
			return x;
		}

		// Crockford base32 (upper case, as generated by Base32Plain) to bytes; exact length required.
		bool Base32Decode(const std::string& s, uint8_t* out, size_t n)
		{
			static const char kA[] = "0123456789ABCDEFGHJKMNPQRSTVWXYZ";
			uint32_t acc = 0;
			int bits = 0;
			size_t o = 0;
			for (char c : s)
			{
				const char* p = std::strchr(kA, c);
				if (!c || !p)
					return false;
				acc = (acc << 5) | static_cast<uint32_t>(p - kA);
				bits += 5;
				if (bits >= 8)
				{
					if (o >= n)
						return false;
					out[o++] = static_cast<uint8_t>(acc >> (bits - 8));
					bits -= 8;
					acc &= (1u << bits) - 1;
				}
			}
			return o == n && acc == 0;
		}

		std::string Hex(const uint8_t* p, size_t n)
		{
			static const char h[] = "0123456789abcdef";
			std::string s;
			for (size_t i = 0; i < n; i++)
			{
				s.push_back(h[p[i] >> 4]);
				s.push_back(h[p[i] & 15]);
			}
			return s;
		}

		// RFC 8445 priority as libjuice computes it for UDP, component 1 (ice.c ice_compute_priority).
		uint32_t CandPriority(const Candidate& c, int index)
		{
			uint32_t tp = 0;
			switch (c.type)
			{
				case CandType::Host: tp = 126; break;
				case CandType::Prflx: tp = 110; break;
				case CandType::Srflx: tp = 100; break;
				case CandType::Relay: tp = 0; break;
			}
			const uint32_t local = (c.ipv6 ? 8191u : 4095u) - static_cast<uint32_t>(std::min(index, 4095));
			return (((tp << 16) + local) << 8) + 255u;
		}

		std::string BuildSdp(const std::string& ufrag, const std::string& pwd, const std::vector<Candidate>& cands, bool end)
		{
			std::string s = "a=ice-ufrag:" + ufrag + "\r\na=ice-pwd:" + pwd + "\r\n";
			int i = 0;
			for (const Candidate& c : cands)
			{
				if (c.type == CandType::Prflx)
					continue; // libjuice's parser ignores prflx
				char line[256];
				std::snprintf(line, sizeof(line), "a=candidate:%d 1 UDP %u %s %u typ %s%s\r\n", i + 1, CandPriority(c, i),
					c.AddrString().c_str(), c.port, c.TypeName(),
					(c.type == CandType::Srflx || c.type == CandType::Relay) ? " raddr 0.0.0.0 rport 0" : "");
				s += line;
				i++;
			}
			if (end)
				s += "a=end-of-candidates\r\n";
			return s;
		}

		bool ParseCandidateSdp(const char* line, Candidate* out)
		{
			const char* p = std::strstr(line, "candidate:");
			if (!p)
				return false;
			p += 10;
			char found[64], transport[16], host[128], type[16];
			unsigned comp = 0, prio = 0, port = 0;
			if (std::sscanf(p, "%63s %u %15s %u %127s %u typ %15s", found, &comp, transport, &prio, host, &port, type) != 7)
				return false;
			if (_stricmp(transport, "UDP") != 0)
				return false;
			CandType t;
			if (!std::strcmp(type, "host"))
				t = CandType::Host;
			else if (!std::strcmp(type, "srflx"))
				t = CandType::Srflx;
			else if (!std::strcmp(type, "prflx"))
				t = CandType::Prflx;
			else if (!std::strcmp(type, "relay"))
				t = CandType::Relay;
			else
				return false;
			return Candidate::FromString(host, static_cast<uint16_t>(port), t, out);
		}

		std::string MaskCand(const Candidate& c)
		{
			char b[96];
			std::snprintf(b, sizeof(b), "%s %s %s port %u", c.TypeName(), c.ipv6 ? "IPv6" : "IPv4", c.ClassName().c_str(),
				c.port);
			return b;
		}

		std::string MaskSdpCand(const char* sdp)
		{
			Candidate c;
			if (ParseCandidateSdp(sdp, &c))
				return MaskCand(c);
			return "(unparsed)";
		}

		// Replaces IPv4/IPv6 addresses in a libjuice log line by their class, and hides password values.
		std::string MaskLine(const std::string& in)
		{
			std::string out;
			size_t i = 0;
			while (i < in.size())
			{
				const char c = in[i];
				const bool start = std::isxdigit(static_cast<unsigned char>(c)) || c == ':';
				if (start && (i == 0 || !std::isalnum(static_cast<unsigned char>(in[i - 1]))))
				{
					size_t j = i;
					while (j < in.size() && (std::isxdigit(static_cast<unsigned char>(in[j])) || in[j] == ':' || in[j] == '.'))
						j++;
					std::string tok = in.substr(i, j - i);
					// strip a trailing ":port" from IPv4
					std::string addr = tok;
					size_t colon = tok.rfind(':');
					if (tok.find('.') != std::string::npos && colon != std::string::npos && tok.find(':') == colon)
						addr = tok.substr(0, colon);
					Candidate cand;
					if ((addr.find('.') != std::string::npos || std::count(addr.begin(), addr.end(), ':') >= 2) &&
						Candidate::FromString(addr, 0, CandType::Host, &cand))
					{
						out += "<" + cand.ClassName() + (cand.ipv6 ? " IPv6" : " IPv4") + ">";
						if (addr.size() < tok.size())
							out += tok.substr(addr.size());
						i = j;
						continue;
					}
					out += tok;
					i = j;
					continue;
				}
				out.push_back(c);
				i++;
			}
			const size_t pw = out.find("password=\"");
			if (pw != std::string::npos)
			{
				const size_t e = out.find('"', pw + 10);
				out.replace(pw + 10, (e == std::string::npos ? out.size() : e) - (pw + 10), "***");
			}
			return out;
		}

		void JuiceLog(juice_log_level_t level, const char* message)
		{
			static std::mutex mx;
			static std::string last;
			static int repeats = 0;
			static const char* names[] = {"verbose", "debug", "info", "warn", "error", "fatal", "none"};
			std::lock_guard<std::mutex> lock(mx);
			const std::string m = MaskLine(message ? message : "");
			if (m == last)
			{
				repeats++;
				if ((repeats & (repeats - 1)) == 0)
					Log("juice[%s]: %s (repeated %d times)", names[level], m.c_str(), repeats);
				return;
			}
			last = m;
			repeats = 1;
			Log("juice[%s]: %s", names[level], m.c_str());
		}

		float Pct(std::vector<float> v, double q)
		{
			if (v.empty())
				return -1.0f;
			std::sort(v.begin(), v.end());
			size_t idx = static_cast<size_t>(std::ceil(q * static_cast<double>(v.size()))) ;
			idx = idx == 0 ? 0 : idx - 1;
			if (idx >= v.size())
				idx = v.size() - 1;
			return v[idx];
		}

		std::string Histogram(const std::vector<float>& v)
		{
			static const float edges[] = {0.5f, 1, 2, 5, 10, 20, 50, 100, 200};
			int counts[10] = {};
			for (float x : v)
			{
				int k = 0;
				while (k < 9 && x >= edges[k])
					k++;
				counts[k]++;
			}
			char b[256];
			std::snprintf(b, sizeof(b), "<0.5:%d 0.5-1:%d 1-2:%d 2-5:%d 5-10:%d 10-20:%d 20-50:%d 50-100:%d 100-200:%d >=200:%d",
				counts[0], counts[1], counts[2], counts[3], counts[4], counts[5], counts[6], counts[7], counts[8], counts[9]);
			return b;
		}

