	void Helper::CbState(juice_agent_t* a, juice_state_t s, void* user)
	{
		Link* L = static_cast<Link*>(user);
		if (L->agent.load() != a)
			return; // an agent that is being replaced
		const int64_t now = NowUs();
		if ((s == JUICE_STATE_CONNECTED || s == JUICE_STATE_COMPLETED) && L->conn_cb_us.load() == 0)
			L->conn_cb_us.store(now);
		L->state_us.store(now);
		L->state.store(s);
	}

	void Helper::CbCandidate(juice_agent_t*, const char*, void*) {}

	void Helper::CbGatheringDone(juice_agent_t* a, void* user)
	{
		Link* L = static_cast<Link*>(user);
		if (L->agent.load() == a)
			L->gathering_done.store(true);
	}

	void Helper::CbRecv(juice_agent_t* a, const char* data, size_t size, void* user)
	{
		Link* L = static_cast<Link*>(user);
		if (L->agent.load() != a)
			return;
		L->owner->OnRecv(L, reinterpret_cast<const uint8_t*>(data), size);
	}

	void Helper::CbMuxIncoming(const juice_mux_binding_request_t* info, void* user)
	{
		Helper* h = static_cast<Helper*>(user);
		Incoming in;
		in.local_ufrag = info->local_ufrag ? info->local_ufrag : "";
		in.remote_ufrag = info->remote_ufrag ? info->remote_ufrag : "";
		in.address = info->address ? info->address : "";
		in.port = info->port;
		std::lock_guard<std::mutex> lock(h->q_mx_);
		if (h->incoming_.size() < 64)
			h->incoming_.push_back(std::move(in));
	}

