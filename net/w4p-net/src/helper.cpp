	void Helper::SetupHostJoinerCreds(Link* L, bool host_side)
	{
		const uint8_t* n = L->nonce.data();
		uint8_t k[16];
		const std::string ju = "J" + Base32Plain(n, kNonceSize);
		DeriveKey16(secret_.data(), "jp", n, kNonceSize, k);
		const std::string jp = Base32Plain(k, 16);
		uint8_t hu8[8];
		Put64(hu8, Prf(secret_.data(), "hu", n, kNonceSize));
		const std::string hu = "H" + Base32Plain(hu8, 8);
		DeriveKey16(secret_.data(), "hp", n, kNonceSize, k);
		const std::string hp = Base32Plain(k, 16);
		if (host_side)
			L->lufrag = hu, L->lpwd = hp, L->rufrag = ju, L->rpwd = jp;
		else
			L->lufrag = ju, L->lpwd = jp, L->rufrag = hu, L->rpwd = hp;
		DeriveKey16(secret_.data(), "mk", n, kNonceSize, L->key);
	}

	void Helper::SetupPairCreds(Link* L, int my, int peer)
	{
		const uint8_t lo = static_cast<uint8_t>(std::min(my, peer));
		const uint8_t hi = static_cast<uint8_t>(std::max(my, peer));
		auto creds = [&](int side, std::string* u, std::string* p) {
			uint8_t extra[kNonceSize + 3];
			std::memcpy(extra, L->nonce.data(), kNonceSize);
			extra[kNonceSize] = lo;
			extra[kNonceSize + 1] = hi;
			extra[kNonceSize + 2] = static_cast<uint8_t>(side);
			uint8_t u8[8], k[16];
			Put64(u8, Prf(secret_.data(), "pu", extra, sizeof(extra)));
			*u = "P" + Base32Plain(u8, 8);
			DeriveKey16(secret_.data(), "pp", extra, sizeof(extra), k);
			*p = Base32Plain(k, 16);
		};
		const int mine = my == lo ? 0 : 1;
		creds(mine, &L->lufrag, &L->lpwd);
		creds(1 - mine, &L->rufrag, &L->rpwd);
		uint8_t extra[kNonceSize + 2];
		std::memcpy(extra, L->nonce.data(), kNonceSize);
		extra[kNonceSize] = lo;
		extra[kNonceSize + 1] = hi;
		DeriveKey16(secret_.data(), "pk", extra, sizeof(extra), L->key);
	}

	void Helper::StartAgent(Link* L)
	{
		juice_config_t c = {};
		c.concurrency_mode = JUICE_CONCURRENCY_MODE_MUX;
		if (opt_.stun)
		{
			c.stun_server_host = opt_.stun_host.c_str();
			c.stun_server_port = static_cast<uint16_t>(opt_.stun_port);
		}
		c.bind_address = opt_.bind_addr.empty() ? nullptr : opt_.bind_addr.c_str();
		c.local_port_range_begin = c.local_port_range_end = static_cast<uint16_t>(ice_port_);
		c.cb_state_changed = &Helper::CbState;
		c.cb_candidate = &Helper::CbCandidate;
		c.cb_gathering_done = &Helper::CbGatheringDone;
		c.cb_recv = &Helper::CbRecv;
		c.user_ptr = L;
		juice_agent_t* a = juice_create(&c);
		if (!a)
		{
			Log("link %d: juice_create failed", L->index);
			return;
		}
		if (juice_set_local_ice_attributes(a, L->lufrag.c_str(), L->lpwd.c_str()) != 0)
			Log("link %d: juice_set_local_ice_attributes failed", L->index);
		L->gathering_done.store(false);
		L->state.store(JUICE_STATE_DISCONNECTED);
		L->conn_cb_us.store(0);
		L->seen_state = -1;
		{
			std::unique_lock<std::shared_mutex> lock(L->agent_mx);
			L->agent.store(a);
		}
		const std::vector<Candidate> rc = L->blocked ? std::vector<Candidate>() : L->remote_cands;
		const std::string sdp = BuildSdp(L->rufrag, L->rpwd, rc, L->remote_end && !rc.empty());
		L->attempts++;
		L->agent_start_us = NowUs();
		if (!L->first_start_us)
			L->first_start_us = L->agent_start_us;
		if (L->controlling)
		{
			juice_gather_candidates(a);
			juice_set_remote_description(a, sdp.c_str());
		}
		else
		{
			juice_set_remote_description(a, sdp.c_str());
			juice_gather_candidates(a);
		}
		Log("link %d (%s, peer slot %d, %s): agent #%d started, %zu remote candidate(s)%s", L->index, KindName(L->kind),
			L->peer_slot.load(), L->controlling ? "controlling" : "controlled", L->attempts, rc.size(),
			L->blocked ? " [TEST SWITCH: direct link blocked]" : "");
		if (L->attempts == 1)
			for (const Candidate& rcand : rc)
				Log("  remote candidate: %s", MaskCand(rcand).c_str());
	}

	void Helper::StopAgent(Link* L)
	{
		juice_agent_t* a = nullptr;
		{
			std::unique_lock<std::shared_mutex> lock(L->agent_mx);
			a = L->agent.exchange(nullptr);
		}
		if (a)
			juice_destroy(a); // outside the lock: the mux thread may be inside OnRecv waiting for this lock
		L->state.store(JUICE_STATE_DISCONNECTED);
	}

	Link* Helper::FindByNonce(const std::array<uint8_t, kNonceSize>& n)
	{
		for (auto& l : links_)
			if (l->kind == Link::Kind::HostToJoiner && l->nonce == n)
				return l.get();
		return nullptr;
	}

	int Helper::FreeSlot(int want) const
	{
		if (want >= 1 && want < players_ && !slot_link_[want].load())
			return want;
		for (int s = 1; s < players_; s++)
			if (!slot_link_[s].load())
				return s;
		return -1;
	}

