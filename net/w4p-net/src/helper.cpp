	bool Helper::OpenMux()
	{
		const char* bind = opt_.bind_addr.empty() ? nullptr : opt_.bind_addr.c_str();
		for (int p = opt_.ice_port; p < opt_.ice_port + 20 && p < 65536; p++)
		{
			if (juice_mux_listen(bind, p, &Helper::CbMuxIncoming, this) == 0)
			{
				ice_port_ = p;
				Log("ICE socket: UDP port %d (MUX mode, one socket for all links), bind %s", p,
					bind ? (include_loopback_ ? "loopback" : "given address") : "all interfaces");
				Event("listen %d", p);
				return true;
			}
		}
		Say("Cannot open a UDP port for the connection (tried %d-%d). Close other copies of w4p-net and try again.",
			opt_.ice_port, opt_.ice_port + 19);
		Event("error ice_port");
		return false;
	}

	bool Helper::GatherHostCandidates(std::vector<Candidate>* out)
	{
		// A temporary agent on the shared MUX socket learns the local candidates (host, and srflx via STUN).
		struct Done
		{
			std::atomic<bool> done{false};
		} d;
		juice_config_t c = {};
		c.concurrency_mode = JUICE_CONCURRENCY_MODE_MUX;
		if (opt_.stun)
		{
			c.stun_server_host = opt_.stun_host.c_str();
			c.stun_server_port = static_cast<uint16_t>(opt_.stun_port);
		}
		c.bind_address = opt_.bind_addr.empty() ? nullptr : opt_.bind_addr.c_str();
		c.local_port_range_begin = c.local_port_range_end = static_cast<uint16_t>(ice_port_);
		c.cb_gathering_done = [](juice_agent_t*, void* u) { static_cast<Done*>(u)->done.store(true); };
		c.user_ptr = &d;
		juice_agent_t* a = juice_create(&c);
		if (!a)
			return false;
		juice_gather_candidates(a);
		const int64_t until = NowUs() + 5000000; // design 4.1: do not wait for STUN longer than a few seconds
		while (!d.done.load() && NowUs() < until)
			std::this_thread::sleep_for(std::chrono::milliseconds(10));
		*out = LocalCandidates(a);
		Log("host candidates gathered in %.1f ms (gathering %s)", (NowUs() - t0_us_) / 1000.0,
			d.done.load() ? "done" : "not finished after 5 s");
		juice_destroy(a);
		return true;
	}

	std::vector<Candidate> Helper::LocalCandidates(juice_agent_t* a)
	{
		std::vector<Candidate> res;
		char sdp[JUICE_MAX_SDP_STRING_LEN];
		if (juice_get_local_description(a, sdp, sizeof(sdp)) != 0)
			return res;
		int host4 = 0, host6 = 0, srflx = 0;
		std::istringstream is(sdp);
		std::string line;
		while (std::getline(is, line))
		{
			Candidate c;
			if (!ParseCandidateSdp(line.c_str(), &c))
				continue;
			if (c.IsLoopback() && !include_loopback_)
				continue;
			if (c.IsLinkLocal())
				continue;
			if (c.type == CandType::Host && !c.ipv6 && host4 >= 3)
				continue;
			if (c.type == CandType::Host && c.ipv6 && host6 >= 1)
				continue;
			if (c.type == CandType::Srflx && srflx >= 2)
				continue;
			if (c.type == CandType::Prflx || c.type == CandType::Relay)
				continue;
			if (c.type == CandType::Host)
				(c.ipv6 ? host6 : host4)++;
			else
				srflx++;
			res.push_back(c);
		}
		return res;
	}

	bool Helper::OpenBridge()
	{
		for (int p = 0; p < kMaxSlots; p++)
		{
			SOCKET s = socket(AF_INET, SOCK_DGRAM, IPPROTO_UDP);
			if (s == INVALID_SOCKET)
				return false;
			BOOL ex = TRUE;
			setsockopt(s, SOL_SOCKET, SO_EXCLUSIVEADDRUSE, reinterpret_cast<const char*>(&ex), sizeof(ex));
			sockaddr_in a = {};
			a.sin_family = AF_INET;
			a.sin_port = htons(static_cast<u_short>(opt_.slot_port_base + p));
			a.sin_addr.s_addr = htonl(INADDR_LOOPBACK);
			if (bind(s, reinterpret_cast<sockaddr*>(&a), sizeof(a)) != 0)
			{
				Say("Cannot open loopback port %d for the emulator (in use?).", opt_.slot_port_base + p);
				Event("error slot_port %d", opt_.slot_port_base + p);
				closesocket(s);
				return false;
			}
			u_long nb = 1;
			ioctlsocket(s, FIONBIO, &nb);
			BOOL f = FALSE;
			DWORD br = 0;
			WSAIoctl(s, SIO_UDP_CONNRESET, &f, sizeof(f), nullptr, 0, &br, nullptr, nullptr);
			int sz = 1 << 20;
			setsockopt(s, SOL_SOCKET, SO_RCVBUF, reinterpret_cast<const char*>(&sz), sizeof(sz));
			setsockopt(s, SOL_SOCKET, SO_SNDBUF, reinterpret_cast<const char*>(&sz), sizeof(sz));
			slot_sock_[p] = static_cast<uintptr_t>(s);
		}
		Log("emulator bridge: emulator at loopback port %d, helper slot ports %d-%d (W4P Peer<p> = 127.0.0.1:%d+p)",
			opt_.emu_port, opt_.slot_port_base, opt_.slot_port_base + kMaxSlots - 1, opt_.slot_port_base);
		bridge_thread_ = std::thread([this] { BridgeThread(); });
		return true;
	}

	void Helper::CloseBridge()
	{
		bridge_stop_.store(true);
		if (bridge_thread_.joinable())
			bridge_thread_.join();
		for (auto& s : slot_sock_)
		{
			if (s != static_cast<uintptr_t>(INVALID_SOCKET))
				closesocket(static_cast<SOCKET>(s));
			s = static_cast<uintptr_t>(INVALID_SOCKET);
		}
	}

