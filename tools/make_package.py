"""Build the 2-PC test package in dist/warriors-4p-test (and a .zip next to it).

Usage: python -I tools/make_package.py
Contents: our PCSX2 build (no debug symbols), the Visual C++ runtime DLLs (app-local), the game patch, the settings
profile, the launcher, README, GPL source pointers and patches, and a SHA-256 manifest. Never any game, ISO, BIOS,
memory card, savestate or extracted game file (BRIEF section 2.4); the build fails if such a file shows up.
"""
import glob
import hashlib
import os
import shutil
import subprocess
import sys
import zipfile

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.path.abspath(os.path.join(HERE, ".."))
BIN = os.path.join(PROJ, "emulator", "pcsx2", "bin")
DEST = os.path.join(PROJ, "dist", "warriors-4p-test")
FORBIDDEN = (".iso", ".bin", ".chd", ".cso", ".rom0", ".rom1", ".rom2", ".erom", ".nvm", ".mec", ".ps2", ".p2s",
             ".elf", ".irx", ".mcd")


def vc_redist_dir():
    installer = os.path.join(os.environ["ProgramFiles(x86)"], "Microsoft Visual Studio", "Installer", "vswhere.exe")
    vs = subprocess.run([installer, "-products", "*", "-latest", "-property", "installationPath"],
                        capture_output=True, text=True).stdout.strip()
    hits = sorted(glob.glob(os.path.join(vs, "VC", "Redist", "MSVC", "*", "x64", "Microsoft.VC14*.CRT")))
    if not hits:
        sys.exit("Visual C++ redistributable folder not found")
    return hits[-1]


def main():
    assert os.path.commonpath([DEST, PROJ]) == PROJ
    if os.path.exists(DEST):
        shutil.rmtree(DEST)
    shutil.copytree(BIN, os.path.join(DEST, "emulator"), ignore=shutil.ignore_patterns("*.pdb", "*.ilk", "*.exp", "*.lib"))
    crt = vc_redist_dir()
    for dll in ("msvcp140.dll", "vcruntime140.dll", "vcruntime140_1.dll"):
        shutil.copy2(os.path.join(crt, dll), os.path.join(DEST, "emulator", dll))
    os.makedirs(os.path.join(DEST, "game"))
    shutil.copy2(os.path.join(PROJ, "mod", "w4p_m1.pnach"), os.path.join(DEST, "game", "w4p.pnach"))
    shutil.copy2(os.path.join(PROJ, "package", "profile_PCSX2.ini"), os.path.join(DEST, "game", "profile_PCSX2.ini"))
    for f in ("Start-Coop.ps1", "Start-Coop.bat", "README.txt"):
        shutil.copy2(os.path.join(PROJ, "package", f), os.path.join(DEST, f))
    src = os.path.join(DEST, "source")
    os.makedirs(src)
    for p in sorted(glob.glob(os.path.join(PROJ, "emulator", "patches", "*.patch"))):
        shutil.copy2(p, src)
    shutil.copy2(os.path.join(PROJ, "mod", "make_pnach.py"), src)
    shutil.copy2(os.path.join(PROJ, "emulator", "pcsx2", "COPYING.GPLv3"), os.path.join(DEST, "COPYING.GPLv3"))
    commit = subprocess.run(["git", "-C", os.path.join(PROJ, "emulator", "pcsx2"), "rev-parse", "HEAD"],
                            capture_output=True, text=True).stdout.strip()
    open(os.path.join(src, "SOURCE.txt"), "w", encoding="utf-8").write(
        "The emulator is PCSX2 v2.9.115 (https://github.com/PCSX2/pcsx2, tag v2.9.115, commit cf3c3720)\n"
        "with the warriors-4p patches in this folder applied in order (git am *.patch).\n"
        f"Build commit of this package: {commit}\n"
        "Build: Visual Studio Build Tools, PCSX2_qt.slnx, target pcsx2-qt, Release x64.\n"
        "The game patch (w4p.pnach) is generated by make_pnach.py.\n"
        "License: GPL-3.0 (COPYING.GPLv3).\n")
    bad = [os.path.relpath(os.path.join(d, f), DEST) for d, _, fs in os.walk(DEST) for f in fs
           if f.lower().endswith(FORBIDDEN) or f.upper().startswith(("SLUS_", "SCUS_"))]
    if bad:
        sys.exit(f"refusing to package forbidden files: {bad}")
    manifest = []
    for d, _, fs in os.walk(DEST):
        for f in sorted(fs):
            p = os.path.join(d, f)
            manifest.append(f"{hashlib.sha256(open(p, 'rb').read()).hexdigest()}  {os.path.relpath(p, DEST)}")
    open(os.path.join(DEST, "MANIFEST.txt"), "w", encoding="utf-8").write("\n".join(sorted(manifest, key=lambda l: l[66:])) + "\n")
    zpath = DEST + ".zip"
    if os.path.exists(zpath):
        os.remove(zpath)
    with zipfile.ZipFile(zpath, "w", zipfile.ZIP_DEFLATED) as z:
        for d, _, fs in os.walk(DEST):
            for f in fs:
                p = os.path.join(d, f)
                z.write(p, os.path.join("warriors-4p-test", os.path.relpath(p, DEST)))
    size = sum(os.path.getsize(os.path.join(d, f)) for d, _, fs in os.walk(DEST) for f in fs)
    print(f"package: {DEST} ({len(manifest)} files, {size / 1e6:.0f} MB); zip {os.path.getsize(zpath) / 1e6:.0f} MB")
    print("emulator build commit:", commit)


if __name__ == "__main__":
    main()
